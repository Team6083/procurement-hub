// Builds the Cloudflare static-assets `_headers` file (CSP and other hardening headers) from the
// validated runtime config (spec section 6.2). The API and OIDC origins are only known from
// APP_CONFIG, so the policy cannot be a static file in public/. Pure: no I/O.

// Cloudflare Web Analytics (auto-injected beacon script and its reporting endpoint).
const CF_INSIGHTS_SCRIPT = 'https://static.cloudflareinsights.com';
const CF_INSIGHTS_CONNECT = 'https://cloudflareinsights.com';

// Anything that reaches the CSP must be a plain https origin. url.origin alone is not enough:
// the URL parser accepts ';', ',', '*' and "'" in a host, which would add directives, split the
// header or create wildcard sources.
const ORIGIN_RE = /^https:\/\/[a-z0-9.-]+(:\d{1,5})?$/;

// Cloudflare silently ignores `_headers` lines longer than this, which would drop the CSP.
const MAX_LINE = 2000;

/**
 * Origin of an https URL (a path is allowed and dropped); throws a message naming `field`
 * otherwise. Userinfo, query and fragment are rejected rather than silently stripped. Hosts are
 * lowercased and IDN hosts become punycode by the URL parser.
 */
export function httpsOrigin(value, field) {
  const shown = JSON.stringify(value);
  let url;
  try {
    url = new URL(value);
  } catch {
    throw new Error(`${field} is not a valid URL: ${shown}`);
  }
  if (url.protocol !== 'https:') {
    throw new Error(`${field} must be an https:// URL (the CSP only allows https origins): ${shown}`);
  }
  if (url.username || url.password || /[?#@]/.test(value)) {
    throw new Error(`${field} must not contain userinfo, a query or a fragment: ${shown}`);
  }
  if (!ORIGIN_RE.test(url.origin)) {
    throw new Error(`${field} has a host that is not a plain hostname (no wildcards or special characters): ${shown}`);
  }
  return url.origin;
}

const unique = (list) => [...new Set(list)];

/** The Content-Security-Policy value for a validated config. */
export function buildCsp(config) {
  const api = httpsOrigin(config?.apiBaseUrl, 'apiBaseUrl');
  const authority = httpsOrigin(config?.oidc?.authority, 'oidc.authority');
  const directives = [
    ['default-src', ["'none'"]],
    ['script-src', ["'self'", CF_INSIGHTS_SCRIPT]],
    // The UI library injects <style> elements at runtime (CSS-in-JS / CSS variables). A static
    // host cannot issue per-response nonces, so inline styles must be allowed.
    ['style-src', ["'self'", "'unsafe-inline'"]],
    // config.json ('self'), the API, the OIDC discovery/token/userinfo endpoints, CF analytics.
    ['connect-src', unique(["'self'", api, authority, CF_INSIGHTS_CONNECT])],
    ['img-src', ["'self'"]],
    ['font-src', ["'self'"]],
    ['frame-ancestors', ["'none'"]],
    ['base-uri', ["'self'"]],
    ['form-action', ["'self'"]],
  ];
  return directives.map(([name, values]) => `${name} ${values.join(' ')}`).join('; ');
}

/** Full `_headers` file text (Cloudflare Workers static assets / Pages syntax). */
export function buildHeaders(config) {
  const lines = [
    '# Generated by scripts/write-config.mjs from APP_CONFIG. Do not edit.',
    '/*',
    `  Content-Security-Policy: ${buildCsp(config)}`,
    '  X-Content-Type-Options: nosniff',
    '  Referrer-Policy: strict-origin-when-cross-origin',
    '  Permissions-Policy: camera=(), microphone=(), geolocation=(), payment=(), usb=()',
    // Hashed file names; index.html and config.json keep Cloudflare's default caching.
    '/assets/*',
    '  Cache-Control: public, max-age=31536000, immutable',
    '',
  ];
  const long = lines.find((l) => l.length > MAX_LINE);
  if (long) throw new Error(`_headers line is ${long.length} characters; Cloudflare ignores lines over ${MAX_LINE}`);
  return lines.join('\n');
}
